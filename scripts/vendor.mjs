// Copies the plugin's runtime packages into its own source folders, so an installed plugin needs
// no node_modules. Paseo compiles the plugin from source with esbuild and supplies only its SDK,
// React, React Native, React Query, and zod; anything else must ship inside client/ or server/.
//
//   client/vendor/codemirror.js   CodeMirror, merge view, and languages as one bundle, so every
//                                 part shares one @codemirror/state (its instanceof checks need it),
//                                 with codemirror.d.ts holding all of their types: Paseo resolves
//                                 type imports too, so they cannot point into node_modules either
//   server/vendor/material-icons/ Material Icon Theme's file-icon map and the SVGs it names
//
// Run after adding or updating those devDependencies: npm run vendor
import { build } from "esbuild";
import { createRequire } from "node:module";
import { rollup } from "rollup";
import { dts } from "rollup-plugin-dts";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "package.json"));

/** Bundle export name to package; the client reads them as `codemirror().<name>` */
const CODEMIRROR_PACKAGES = {
  state: "@codemirror/state",
  view: "@codemirror/view",
  language: "@codemirror/language",
  merge: "@codemirror/merge",
  themeOneDark: "@codemirror/theme-one-dark",
  langCpp: "@codemirror/lang-cpp",
  langCss: "@codemirror/lang-css",
  langGo: "@codemirror/lang-go",
  langHtml: "@codemirror/lang-html",
  langJava: "@codemirror/lang-java",
  langJavascript: "@codemirror/lang-javascript",
  langJson: "@codemirror/lang-json",
  langMarkdown: "@codemirror/lang-markdown",
  langPython: "@codemirror/lang-python",
  langRust: "@codemirror/lang-rust",
  langXml: "@codemirror/lang-xml",
  langYaml: "@codemirror/lang-yaml",
};

const GENERATED = "// Generated by scripts/vendor.mjs; do not edit.\n";

/** The package directory and name that own a bundled file */
function owningPackage(file) {
  const parts = path.resolve(root, file).split(path.sep);
  const index = parts.lastIndexOf("node_modules");
  if (index === -1) return null;
  const size = parts[index + 1].startsWith("@") ? 2 : 1;
  return {
    name: parts.slice(index + 1, index + 1 + size).join("/"),
    directory: parts.slice(0, index + 1 + size).join(path.sep),
  };
}

function licenseText(directory) {
  const file = readdirSync(directory).find((name) => /^(licen[cs]e|copying)(\.|$)/i.test(name));
  if (!file) throw new Error(`No license file in ${directory}`);
  return readFileSync(path.join(directory, file), "utf8").trim();
}

/** Bundles the re-exported packages' declarations into one file with no imports of its own */
async function bundleDeclarations(reexports, outfile) {
  // rollup-plugin-dts resolves from a real file, so the entry sits where node_modules is visible
  const entry = path.join(root, ".vendor-entry.d.ts");
  writeFileSync(entry, `${reexports}\n`);
  try {
    const bundle = await rollup({ input: entry, plugins: [dts({ respectExternal: true })] });
    const { output } = await bundle.generate({ format: "es" });
    await bundle.close();
    const code = output[0].code;
    const external = code.match(/^\s*(?:import|export)\b[^;]*?\bfrom\s*["'][^"']+["']|\bimport\(\s*["'][^"']+["']/m);
    if (external) throw new Error(`Declarations still import a module: ${external[0]}`);
    writeFileSync(outfile, `${GENERATED}${code}`);
  } finally {
    rmSync(entry, { force: true });
  }
}

async function vendorCodeMirror() {
  const directory = path.join(root, "client", "vendor");
  rmSync(directory, { recursive: true, force: true });
  mkdirSync(directory, { recursive: true });
  const entries = Object.entries(CODEMIRROR_PACKAGES);
  const reexports = entries.map(([name, pkg]) => `export * as ${name} from "${pkg}";`).join("\n");

  const result = await build({
    stdin: { contents: reexports, resolveDir: root, sourcefile: "codemirror-entry.js" },
    bundle: true,
    format: "cjs",
    platform: "neutral",
    mainFields: ["module", "main"],
    target: "es2020",
    minify: true,
    legalComments: "none",
    metafile: true,
    outfile: path.join(directory, "codemirror.js"),
    banner: { js: GENERATED },
  });

  await bundleDeclarations(reexports, path.join(directory, "codemirror.d.ts"));

  const packages = new Map();
  for (const input of Object.keys(result.metafile.inputs)) {
    const owner = owningPackage(input);
    if (owner) packages.set(owner.name, owner.directory);
  }
  const notices = [...packages]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([name, packageDirectory]) => {
      const { version } = JSON.parse(readFileSync(path.join(packageDirectory, "package.json"), "utf8"));
      return `${name}@${version}\n\n${licenseText(packageDirectory)}`;
    });
  writeFileSync(
    path.join(directory, "THIRD_PARTY_LICENSES.txt"),
    `Third-party packages bundled into codemirror.js\n\n${notices.join(`\n\n${"-".repeat(72)}\n\n`)}\n`,
  );
  return packages.size;
}

function vendorMaterialIcons() {
  const packageDirectory = path.dirname(require.resolve("material-icon-theme/package.json"));
  const { generateManifest } = require("material-icon-theme");
  const manifest = generateManifest();
  const definitions = manifest.iconDefinitions ?? {};
  const lowercaseKeys = (record) =>
    Object.fromEntries(Object.entries(record ?? {}).map(([key, icon]) => [key.toLowerCase(), icon]));
  const fileNames = lowercaseKeys(manifest.fileNames);
  const fileExtensions = lowercaseKeys(manifest.fileExtensions);
  const fallback = manifest.file ?? "file";

  // Only file icons are ever shown, each with its light-theme variant where one exists
  const ids = new Set([fallback, ...Object.values(fileNames), ...Object.values(fileExtensions)]);
  for (const id of [...ids]) if (definitions[`${id}_light`]) ids.add(`${id}_light`);
  const iconFiles = {};
  for (const id of [...ids].sort()) {
    const iconPath = definitions[id]?.iconPath;
    if (iconPath) iconFiles[id] = path.posix.basename(iconPath);
  }

  const directory = path.join(root, "server", "vendor", "material-icons");
  rmSync(directory, { recursive: true, force: true });
  mkdirSync(path.join(directory, "icons"), { recursive: true });
  const svgs = new Set(Object.values(iconFiles));
  for (const svg of svgs) {
    const source = path.join(packageDirectory, "icons", svg);
    if (!existsSync(source)) throw new Error(`Material Icon Theme has no ${svg}`);
    copyFileSync(source, path.join(directory, "icons", svg));
  }
  writeFileSync(
    path.join(directory, "manifest.json"),
    `${JSON.stringify({ file: fallback, fileNames, fileExtensions, iconFiles })}\n`,
  );
  const { version } = JSON.parse(readFileSync(path.join(packageDirectory, "package.json"), "utf8"));
  writeFileSync(path.join(directory, "LICENSE"), `material-icon-theme@${version}\n\n${licenseText(packageDirectory)}\n`);
  return svgs.size;
}

const packageCount = await vendorCodeMirror();
const iconCount = vendorMaterialIcons();
console.log(`client/vendor/codemirror.js: ${packageCount} packages`);
console.log(`server/vendor/material-icons: ${iconCount} icons`);
